const POLL_INTERVAL: Duration = Duration::from_millis(100);
/// Web views (Teams, Slack) hold thousands of elements; a bound keeps one scan short.
const MAX_SCAN_NODES: usize = 6_000;
const RETURN_KEY_CODE: u16 = 36;
const PASTE_KEY_CODE: u16 = 9;
const SELECT_ALL_KEY_CODE: u16 = 0;
const DELETE_KEY_CODE: u16 = 51;
/// Zoom's own shortcut to show or hide the meeting chat (Command-Shift-H).
const ZOOM_CHAT_KEY_CODE: u16 = 4;
/// How long the app may take to come to the front, take the text, or clear its input.
const STEP_TIMEOUT: Duration = Duration::from_millis(2_000);
/// The app needs to read the clipboard before it is put back.
const PASTEBOARD_RESTORE_DELAY: Duration = Duration::from_millis(400);
const TRANSIENT_TYPES: [&str; 2] = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

#[derive(Default)]
struct Scan {
    call: bool,
    input: Option<CFRetained<AXUIElement>>,
    open_chat: Option<CFRetained<AXUIElement>>,
    /// The window holding the call, raised before any key is pressed.
    window: Option<CFRetained<AXUIElement>>,
}

pub(super) fn post_notice(
    app: NativeMeetingApp,
    pid: i32,
    message: &str,
    timeout: Duration,
    cancelled: &dyn Fn() -> bool,
) -> Result<Outcome> {
    if !is_accessibility_trusted() || !can_post_key_events() {
        return Err(Error::PermissionRequired);
    }
    let _guard = lock_meeting_app();
    // The camera switch may have held the lock for a while.
    if cancelled() {
        return Ok(Outcome::Cancelled);
    }
    // The confirmed process may have quit and its pid been reused by another app.
    if pid <= 0 || bundle_id_of(pid).as_deref() != Some(app.bundle_id()) {
        return Ok(Outcome::NoCall);
    }
    let deadline = Instant::now() + timeout;
    let application = unsafe { AXUIElement::new_application(pid) };
    let previous = frontmost_pid();
    let found = scan_at_front(app, pid, &application, deadline)?;
    if !found.call {
        give_front_back(previous, pid);
        return Ok(Outcome::NoCall);
    }
    post_in_call(
        app,
        pid,
        &application,
        found,
        message,
        previous,
        deadline,
        cancelled,
    )
}

/// The app's call and chat, bringing the app to the front first when it shows its call only there.
fn scan_at_front(
    app: NativeMeetingApp,
    pid: i32,
    application: &AXUIElement,
    deadline: Instant,
) -> Result<Scan> {
    let found = scan(app, application)?;
    if found.call || !app.shows_call_only_in_front() || !bring_to_front(pid, application, None) {
        return Ok(found);
    }
    let until = deadline.min(Instant::now() + STEP_TIMEOUT);
    loop {
        let found = scan(app, application)?;
        if found.call || Instant::now() >= until {
            return Ok(found);
        }
        thread::sleep(POLL_INTERVAL);
    }
}

#[allow(clippy::too_many_arguments)]
fn post_in_call(
    app: NativeMeetingApp,
    pid: i32,
    application: &AXUIElement,
    mut found: Scan,
    message: &str,
    previous: Option<i32>,
    deadline: Instant,
    cancelled: &dyn Fn() -> bool,
) -> Result<Outcome> {
    let outcome = (|| {
        if found.input.is_none() {
            if cancelled() {
                return Ok(Outcome::Cancelled);
            }
            // Zoom lays out its chat panel only at the front: pressed from the background, the
            // button takes the press and nothing opens.
            if !bring_to_front(pid, application, found.window.as_deref()) {
                return Ok(Outcome::NotSent);
            }
            // At the front, a chat that was open all along shows; pressing would close it.
            found = scan(app, application)?;
            if found.input.is_none()
                && let Some(control) = found.open_chat.as_deref()
            {
                let _ = press(control);
                found = wait_for_input(
                    app,
                    application,
                    deadline.min(Instant::now() + STEP_TIMEOUT),
                )?;
            }
            // Zoom's chat button can sit in the toolbar's overflow; its shortcut opens it either
            // way. It goes only to Zoom at the front, after the press showed no chat input for a
            // whole step, so it opens the chat rather than closing it.
            if found.input.is_none()
                && app == NativeMeetingApp::Zoom
                && frontmost_pid() == Some(pid)
                && post_key_chord_to_pid(
                    pid,
                    ZOOM_CHAT_KEY_CODE,
                    &[KeyModifier::Command, KeyModifier::Shift],
                )
            {
                found = wait_for_input(app, application, deadline)?;
            }
        }
        let Some(input) = found.input.as_deref() else {
            return Ok(Outcome::ChatUnavailable);
        };
        if !is_empty_draft(&value_of(input), &placeholder_of(input)) {
            return Ok(Outcome::DraftInProgress);
        }
        if cancelled() {
            return Ok(Outcome::Cancelled);
        }
        if !bring_to_front(pid, application, found.window.as_deref()) {
            return Ok(Outcome::NotSent);
        }
        Ok(deliver(&AxChatInput { pid, input }, message, cancelled))
    })();
    // Give the front back to whatever had it, unless the person moved on meanwhile.
    give_front_back(previous, pid);
    outcome
}

/// The call's chat input over Accessibility; keys go to the app's process.
struct AxChatInput<'a> {
    pid: i32,
    input: &'a AXUIElement,
}

impl ChatInput for AxChatInput<'_> {
    fn value(&self) -> String {
        value_of(self.input)
    }

    fn placeholder(&self) -> String {
        placeholder_of(self.input)
    }

    fn set_value(&self, text: &str) -> bool {
        set_attribute(self.input, "AXValue", CFString::from_str(text).as_ref())
    }

    fn focus(&self) {
        let _ = focus(self.input, self.pid);
    }

    fn can_type(&self) -> bool {
        is_frontmost_with_focus(self.pid, self.input)
    }

    fn paste(&self, text: &str) -> bool {
        paste_to_pid(self.pid, text)
    }

    fn erase(&self) -> bool {
        post_key_chord_to_pid(self.pid, SELECT_ALL_KEY_CODE, &[KeyModifier::Command])
            && post_key_chord_to_pid(self.pid, DELETE_KEY_CODE, &[])
    }

    fn can_send(&self) -> bool {
        is_frontmost_with_focus(self.pid, self.input)
    }

    fn send(&self) -> bool {
        post_key_chord_to_pid(self.pid, RETURN_KEY_CODE, &[])
    }

    fn wait_until(&self, ready: &mut dyn FnMut() -> bool) -> bool {
        wait_until(ready)
    }
}

/// Scans until the call shows its chat input or `until` passes; the last scan either way.
fn wait_for_input(
    app: NativeMeetingApp,
    application: &AXUIElement,
    until: Instant,
) -> Result<Scan> {
    loop {
        let found = scan(app, application)?;
        if found.input.is_some() || Instant::now() >= until {
            return Ok(found);
        }
        thread::sleep(POLL_INTERVAL);
    }
}

/// One pass over the app's windows: is a call on, and where are its chat input and chat button.
/// Inputs and buttons count only inside the call's own window (and for Slack, inside the huddle),
/// so a notice can never land in an ordinary channel or chat.
fn scan(app: NativeMeetingApp, application: &AXUIElement) -> Result<Scan> {
    let mut result = Scan::default();
    for window in app_windows(application)? {
        let identifier = string_attribute(&window, "AXIdentifier")?.unwrap_or_default();
        let window_call = is_call_window(app, &identifier, &dom_classes(&window)?);
        let mut stack = vec![(window.clone(), window_call)];
        // Zoom's toolbar buttons list themselves among their own children; without this the
        // scan loops on them and runs out of nodes before it reaches the chat.
        let mut seen = HashSet::new();
        let mut visited = 0_usize;
        let mut call = window_call;
        let mut input = None;
        let mut open_chat = None;
        while let Some((element, inside_call)) = stack.pop() {
            if !seen.insert(element.clone()) {
                continue;
            }
            visited += 1;
            if visited > MAX_SCAN_NODES {
                break;
            }
            let role = role_attribute(&element)?;
            let classes = dom_classes(&element)?;
            let labels = labels_of(&element, &classes)?;
            let identifier = string_attribute(&element, "AXIdentifier")?.unwrap_or_default();
            let marks_call = match app {
                NativeMeetingApp::Zoom => false,
                NativeMeetingApp::Teams => is_teams_call_marker(&role, &labels),
                NativeMeetingApp::Webex => is_webex_call_marker(&role, &identifier),
                NativeMeetingApp::Slack => {
                    is_call_window(app, "", &classes)
                        || classes
                            .iter()
                            .any(|class| class == "p-view_contents--huddle")
                }
            };
            call |= marks_call;
            let inside = inside_call || marks_call;
            // Teams and Webex mark the call with controls beside the chat, not around it: the
            // window counts.
            let in_scope =
                inside || matches!(app, NativeMeetingApp::Teams | NativeMeetingApp::Webex);
            if in_scope && input.is_none() && is_chat_input(app, &role, &labels) {
                input = Some(element.clone());
            }
            if in_scope
                && open_chat.is_none()
                && is_open_chat_control(app, &role, &identifier, &labels)
            {
                open_chat = Some(element.clone());
            }
            for child in children(&element)?.into_iter().rev() {
                stack.push((child, inside));
            }
        }
        if call {
            let has_chat = input.is_some() || open_chat.is_some();
            // Teams floats a compact view of the call, with its controls but no chat, while it
            // isn't at the front: a call window that holds the chat wins over it.
            if has_chat || !result.call {
                result.call = true;
                result.window = Some(window.clone());
                result.input = input;
                result.open_chat = open_chat;
            }
            if has_chat {
                return Ok(result);
            }
        }
    }
    Ok(result)
}

fn labels_of(element: &AXUIElement, classes: &[String]) -> Result<Vec<String>> {
    let mut labels = Vec::new();
    for attribute in ["AXTitle", "AXDescription", "AXPlaceholderValue", "AXHelp"] {
        if let Some(value) = string_attribute(element, attribute)? {
            labels.push(value);
        }
    }
    labels.extend(classes.iter().cloned());
    Ok(labels)
}

fn value_of(element: &AXUIElement) -> String {
    string_attribute(element, "AXValue")
        .ok()
        .flatten()
        .unwrap_or_default()
}

fn placeholder_of(element: &AXUIElement) -> String {
    string_attribute(element, "AXPlaceholderValue")
        .ok()
        .flatten()
        .unwrap_or_default()
}

/// Keys go only to the call's app at the front, typing into the chat input: if the person switched
/// apps or moved focus meanwhile, nothing is pressed.
fn is_frontmost_with_focus(pid: i32, input: &AXUIElement) -> bool {
    if frontmost_pid() != Some(pid) {
        return false;
    }
    let application = unsafe { AXUIElement::new_application(pid) };
    let focused = element_attribute(&application, "AXFocusedUIElement")
        .ok()
        .flatten();
    focused.is_some_and(|focused| *focused == *input)
}

/// Pastes through the general pasteboard and puts the person's clipboard back once the app has
/// read it, unless something else changed it meanwhile.
fn paste_to_pid(pid: i32, text: &str) -> bool {
    let text = text.to_string();
    run_on_main_thread(move || {
        let pasteboard = NSPasteboard::generalPasteboard();
        let snapshot = PasteboardSnapshot::capture(&pasteboard);
        let markers = TRANSIENT_TYPES.map(NSString::from_str);
        let mut types = vec![unsafe { NSPasteboardTypeString }];
        types.extend(markers.iter().map(|marker| &**marker));
        // SAFETY: no owner object, so no lazy-provider callbacks.
        unsafe { pasteboard.declareTypes_owner(&NSArray::from_slice(&types), None) };
        if !pasteboard.setString_forType(&NSString::from_str(&text), unsafe {
            NSPasteboardTypeString
        }) {
            snapshot.restore(&pasteboard);
            return false;
        }
        for marker in &markers {
            pasteboard.setData_forType(Some(&NSData::new()), marker);
        }
        let change = pasteboard.changeCount();
        if !post_key_chord_to_pid(pid, PASTE_KEY_CODE, &[KeyModifier::Command]) {
            snapshot.restore(&pasteboard);
            return false;
        }
        thread::spawn(move || {
            thread::sleep(PASTEBOARD_RESTORE_DELAY);
            run_on_main_thread(move || {
                let pasteboard = NSPasteboard::generalPasteboard();
                snapshot.restore_if_unchanged(&pasteboard, change, Some(&text));
            });
        });
        true
    })
}

fn wait_until(ready: &mut dyn FnMut() -> bool) -> bool {
    let deadline = Instant::now() + STEP_TIMEOUT;
    loop {
        if ready() {
            return true;
        }
        if Instant::now() >= deadline {
            return false;
        }
        thread::sleep(POLL_INTERVAL);
    }
}
